function overlay(rows: string[], layer: string[]) {
  return rows.map((r, y) => {
    const l = layer[y];
    if (!l) return r;
    let out = '';
    for (let x = 0; x < 16; x++) out += l[x] && l[x] !== '.' ? l[x] : r[x];
    return out;
  });
}

export function npcFrames(def: NpcDef) {
  let rows = BASE_NPC.slice();
  for (const name of def.layers) rows = overlay(rows, LAYERS[name]);
  const setAt = (rs: string[], y: number, x: number, ch: string) => rs.map((r, i) => (i === y ? r.slice(0, x) + ch + r.slice(x + 1) : r));
  let blink = setAt(rows, 6, 6, 'p'); blink = setAt(blink, 6, 9, 'p');
  let talk = setAt(rows, 8, 7, 'k'); talk = setAt(talk, 8, 8, 'k');
  return { base: rows, blink, talk, bob: bob(rows) };
}

