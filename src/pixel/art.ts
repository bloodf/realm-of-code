// ---------- Hero animation frames ----------
// Walking: swap the two bottom rows (legs); idle: a 1px "breathing" bob.
const LEGS: Record<string, [string, string][]> = {
  knight: [['...kdk...kdk....', '...kkk...kkk....'], ['.....kdkdk......', '.....kkkkk......']],
  ranger: [['...kNk...kNk....', '...kkk...kkk....'], ['.....kNkNk......', '.....kkkkk......']],
  mage: [['..krrrrrrRRk....', '...kkkkkkkk.....'], ['....krrrrrrRRk..', '.....kkkkkkkk...']],
  goblin: [['...kGk...kGk....', '...kkk...kkk....'], ['.....kGkGk......', '.....kkkkk......']],
};

function bob(rows: string[]) {
  const empty = '.'.repeat(16);
  return [empty, ...rows.slice(0, 13), rows[14], rows[15]];
}

export function heroFrames(sprites: Record<string, string[]>) {
  const out: Record<string, string[]> = {};
  for (const [name, legs] of Object.entries(LEGS)) {
    const base = sprites[name];
    if (!base) continue;
    out[`${name}@walk1`] = [...base.slice(0, 14), ...legs[0]];
    out[`${name}@walk2`] = [...base.slice(0, 14), ...legs[1]];
    out[`${name}@bob`] = bob(base);
  }
  // Ember: blink and tail wag
  const ember = sprites.ember;
  if (ember) {
    out['ember@blink'] = ember.map((r, y) => (y === 5 ? r.replace(/e/g, 'k') : y === 4 ? r.replace(/w/g, 'o') : r));
    out['ember@tail'] = ember.map((r, y) => (y >= 5 && y <= 7 ? '.' + r.slice(0, 7) + r.slice(8) : r));
    out['ember@bob'] = bob(ember);
  }
  return out;
}

