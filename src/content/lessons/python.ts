/** Python probe: evaluates each expression after your program (errors become "ERR:Name"). */
export function pyProbe(exprs: Record<string, string>) {
  const items = Object.entries(exprs).map(([k, e]) => `(${JSON.stringify(k)}, ${JSON.stringify(e)})`).join(', ');
  return `__probe = {}\nfor __k, __e in [${items}]:\n    try:\n        __probe[__k] = eval(__e)\n    except Exception as __x:\n        __probe[__k] = "ERR:" + type(__x).__name__`;
}
/** Code without Python comments (for "did you use X" checks). */
